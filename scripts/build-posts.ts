/* Compiles content/blog/*.md into src/data/posts.generated.ts so the app, the
   SSR bundle and the node scripts (sitemap, IndexNow) all read the same typed
   data without a Markdown loader. Run: npm run posts */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const sourceDir = path.join(root, 'content', 'blog');
const outFile = path.join(root, 'src', 'data', 'posts.generated.ts');

type Frontmatter = Record<string, string | string[]>;

function parseFrontmatter(raw: string, file: string): { data: Frontmatter; body: string } {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw.replace(/\r\n/g, '\n'));
  if (!match) throw new Error(`${file}: missing frontmatter`);

  const data: Frontmatter = {};
  let listKey: string | null = null;
  for (const line of match[1].split('\n')) {
    if (!line.trim()) continue;
    const item = /^\s+-\s+(.*)$/.exec(line);
    if (item && listKey) {
      (data[listKey] as string[]).push(item[1].trim().replace(/^"(.*)"$/, '$1'));
      continue;
    }
    const pair = /^([A-Za-z]+):\s*(.*)$/.exec(line);
    if (!pair) throw new Error(`${file}: cannot read frontmatter line "${line}"`);
    const [, key, value] = pair;
    if (value === '') {
      data[key] = [];
      listKey = key;
    } else {
      data[key] = value.trim().replace(/^"(.*)"$/, '$1');
      listKey = null;
    }
  }
  return { data, body: match[2].trim() };
}

const required = ['slug', 'title', 'seoTitle', 'description', 'capsule', 'date', 'tags'];

const posts = fs.readdirSync(sourceDir)
  .filter((file) => file.endsWith('.md'))
  .map((file) => {
    const { data, body } = parseFrontmatter(fs.readFileSync(path.join(sourceDir, file), 'utf8'), file);
    for (const key of required) {
      if (!data[key] || (Array.isArray(data[key]) && !(data[key] as string[]).length)) throw new Error(`${file}: missing "${key}"`);
    }
    if (`${data.slug}.md` !== file) throw new Error(`${file}: slug must match the file name`);
    if ((data.seoTitle as string).length > 65) console.warn(`${file}: seoTitle is ${(data.seoTitle as string).length} characters (aim for ≤ 60)`);
    if ((data.description as string).length > 165) console.warn(`${file}: description is ${(data.description as string).length} characters (aim for ≤ 160)`);

    return {
      slug: data.slug,
      title: data.title,
      seoTitle: data.seoTitle,
      description: data.description,
      capsule: data.capsule,
      date: data.date,
      ...(data.updated ? { updated: data.updated } : {}),
      rank: Number(data.rank ?? 99),
      tags: data.tags,
      ...(data.takeaways ? { takeaways: data.takeaways } : {}),
      sections: [],
      markdown: body,
    };
  })
  // Newest first; `rank` (optional frontmatter) orders posts published the same day.
  .sort((a, b) => String(b.updated ?? b.date).localeCompare(String(a.updated ?? a.date)) || a.rank - b.rank)
  .map((post) => {
    const output: Record<string, unknown> = { ...post };
    delete output.rank;
    return output;
  });

const output = `/* Generated by scripts/build-posts.ts from content/blog/*.md — do not edit by hand. */
import type { Article } from './article-types';

export const markdownPosts: Article[] = ${JSON.stringify(posts, null, 2)};
`;

fs.writeFileSync(outFile, output, 'utf8');
console.log(`Wrote ${posts.length} posts to ${path.relative(root, outFile)}`);
